export function searchJordanianLegalReferences(query: string): {
  matches: JordanianStatuteEntry[];
  citations: LegalReferenceCitation[];
} {
  const normalized = query.trim().toLowerCase();
  if (!normalized) {
    return { matches: [], citations: [] };
  }

  const scored = JORDANIAN_STATUTE_INDEX.map((entry) => {
    let score = 0;
    for (const kw of entry.keywords) {
      if (normalized.includes(kw.toLowerCase())) {
        score += 2;
      }
    }
    if (normalized.includes(entry.lawName.toLowerCase())) {
      score += 3;
    }
    return { entry, score };
  })
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 4);

  const matches = scored.map((s) => s.entry);
  const citations: LegalReferenceCitation[] = matches.map((m) => ({
    lawName: m.lawName,
    year: m.lawNumberAndYear,
    note: m.summary,
    verified: true,
  }));

  return { matches, citations };
}
